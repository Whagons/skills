//go:build ignore

// extract.go copies the credential-encryption code out of gonvex/skills.go
// (by AST, not by hand) into a standalone package next to harness.go, so the
// Worker's crypto can be checked against the exact Go implementation without
// a Gonvex checkout. Usage: go build -o extract extract.go && ./extract <skills.go> <out-dir>
package main

import (
	"bytes"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"path/filepath"
)

var wanted = map[string]bool{
	"decodeCredentialKey": true, "newCredentialCipher": true, "credentialCiphers": true,
	"credentialAAD": true, "encryptSecret": true, "decryptSecret": true, "hashToken": true, "splitCSV": true,
	"credentialCipher": true, "credentialKeyConfig": true, "encryptedValuePrefix": true,
}

func main() {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, os.Args[1], nil, parser.ParseComments)
	if err != nil {
		panic(err)
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by extract.go from gonvex/skills.go. DO NOT EDIT.\n\npackage main\n\n")
	out.WriteString("import (\n\t\"crypto/aes\"\n\t\"crypto/cipher\"\n\t\"crypto/rand\"\n\t\"crypto/sha256\"\n\t\"encoding/base64\"\n\t\"encoding/hex\"\n\t\"errors\"\n\t\"fmt\"\n\t\"os\"\n\t\"strings\"\n)\n\n")
	found := map[string]bool{}
	for _, decl := range file.Decls {
		keep := false
		switch d := decl.(type) {
		case *ast.FuncDecl:
			keep = d.Recv == nil && wanted[d.Name.Name]
			if keep {
				found[d.Name.Name] = true
			}
		case *ast.GenDecl:
			for _, spec := range d.Specs {
				switch sp := spec.(type) {
				case *ast.TypeSpec:
					if wanted[sp.Name.Name] {
						keep, found[sp.Name.Name] = true, true
					}
				case *ast.ValueSpec:
					for _, name := range sp.Names {
						if wanted[name.Name] {
							keep, found[name.Name] = true, true
						}
					}
				}
			}
		}
		if keep {
			if err := printer.Fprint(&out, fset, decl); err != nil {
				panic(err)
			}
			out.WriteString("\n\n")
		}
	}
	for name := range wanted {
		if !found[name] {
			panic("gonvex/skills.go no longer defines " + name)
		}
	}
	src, err := format.Source(out.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile(filepath.Join(os.Args[2], "extracted.go"), src, 0o644); err != nil {
		panic(err)
	}
}
